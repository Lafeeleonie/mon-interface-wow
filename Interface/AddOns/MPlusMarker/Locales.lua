-- Apply locale overrides; esMX falls back to esES for any missing keys, then enUS.
local function ApplyLocaleTable(tbl)
    if not tbl then return end
    for k, v in pairs(tbl) do
        L[k] = v
    end
end

if locale == "esMX" then
    ApplyLocaleTable(localized.esES)
    ApplyLocaleTable(localized.esMX)
else
    ApplyLocaleTable(localized[locale])
end

setmetatable(L, {
    __index = function(_, k)
        return enUS[k] or k
    end,
})

addonTable.L = L
